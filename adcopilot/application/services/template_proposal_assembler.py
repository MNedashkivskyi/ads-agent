"""TemplateProposalAssembler — build CampaignProposal from a VerticalTemplate.

Replaces LLM stages 1 (vertical detection) and 2 (campaign structure) in the
hybrid generation path.  Ad copy (stage 3) and additional negative keywords
(stage 4) are still generated by the LLM in GenerateCampaignProposalUseCase.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from decimal import Decimal

from adcopilot.domain.launch.budget_tier import BudgetTier, classify_budget_tier
from adcopilot.domain.launch.entities import (
    AdGroupProposal,
    AdProposal,
    CalloutProposal,
    CampaignBrief,
    CampaignProposal,
    CampaignProposalId,
    KeywordProposal,
    MatchType,
    SitelinkProposal,
    StructuredSnippetProposal,
)
from adcopilot.domain.launch.vertical_template import (
    KeywordPriority,
    TemplateMatchType,
    VerticalTemplate,
)
from adcopilot.domain.polish_market.negative_keywords import POLISH_STANDARD_NEGATIVES

# Placeholder ad copy inserted when the assembler runs without LLM.
# These will be replaced by LLM stage 3 in the hybrid path.
_PLACEHOLDER_HEADLINES = [
    "Najlepsza oferta w {city}",
    "Sprawdź naszą ofertę",
    "Skontaktuj się z nami",
]
_PLACEHOLDER_DESCRIPTIONS = [
    "Profesjonalne usługi dla Twojej firmy. Zadzwoń lub umów się online.",
    "Doświadczony zespół, szybka realizacja. Sprawdź naszą ofertę już dziś.",
]

# Ensure all standard negative categories are covered.
_STANDARD_NEGATIVE_ANCHORS: list[str] = [
    terms[0] for _, terms in POLISH_STANDARD_NEGATIVES
]

_MATCH_TYPE_MAP: dict[TemplateMatchType, MatchType] = {
    TemplateMatchType.EXACT: MatchType.EXACT,
    TemplateMatchType.PHRASE: MatchType.PHRASE,
    TemplateMatchType.BROAD: MatchType.BROAD,
}


def _resolve(text: str, city: str, service: str) -> str:
    """Replace {city} and {service} placeholders."""
    return text.replace("{city}", city).replace("{service}", service)


def _estimate_cpc_micros(tier: BudgetTier, template: VerticalTemplate) -> int:
    """Return a rough CPC estimate in micros based on bidding config for the tier."""
    cfg = template.bidding_defaults.for_tier(tier.value)
    return int(cfg.max_cpc_limit_pln * 1_000_000 * 0.6)


class TemplateProposalAssembler:
    """Assemble a :class:`CampaignProposal` from a :class:`VerticalTemplate` and user inputs.

    The produced proposal is identical in shape to what
    :class:`~adcopilot.application.use_cases.launch.generate_proposal.GenerateCampaignProposalUseCase`
    returns, so it can be passed directly to the validator and Google Ads writer.

    Ad copy fields in the proposal are pre-filled with Polish-language placeholders
    when used standalone.  In the hybrid generation path these are replaced by the
    LLM ad-copy stage before the proposal is persisted.
    """

    def assemble(
        self,
        template: VerticalTemplate,
        brief: CampaignBrief,
        *,
        phone: str | None = None,
    ) -> CampaignProposal:
        """Build and return a :class:`CampaignProposal` from the template + brief.

        Parameters
        ----------
        template:
            The vertical template to use for structure, keywords, and extensions.
        brief:
            The user's campaign brief, providing budget, city, and exclusions.
        phone:
            Optional phone number for the call extension callout.
        """
        city = brief.location.split(",")[0].strip()
        service = (
            template.common_services[0] if template.common_services else "usługi"
        )

        tier = classify_budget_tier(brief.monthly_budget_pln)
        daily_budget_micros = self._calc_daily_budget(brief.monthly_budget_pln)
        bidding_strategy = template.bidding_defaults.for_tier(tier.value).bidding_strategy

        ad_groups = self._build_ad_groups(template, tier, city, service, brief.exclusions)
        negative_keywords = self._build_negatives(template, brief)
        sitelinks = self._build_sitelinks(template)
        callouts = self._build_callouts(template, phone)
        structured_snippets = self._build_structured_snippets(template)
        cpc_micros = _estimate_cpc_micros(tier, template)

        return CampaignProposal(
            id=CampaignProposalId(str(uuid.uuid4())),
            brief_id=brief.id,
            campaign_name=f"{template.display_name} | {city}",
            daily_budget_micros=daily_budget_micros,
            location_targeting=brief.location,
            bidding_strategy=bidding_strategy,
            ad_groups=ad_groups,
            negative_keywords=negative_keywords,
            sitelinks=sitelinks,
            callouts=callouts,
            structured_snippets=structured_snippets,
            estimated_cpc_range=(
                int(cpc_micros * 0.5),
                int(cpc_micros * 1.5),
            ),
            generated_at=datetime.now(UTC),
        )

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _calc_daily_budget(monthly_budget_pln: Decimal) -> int:
        return int(monthly_budget_pln / Decimal("30") * Decimal("1_000_000"))

    def _build_ad_groups(
        self,
        template: VerticalTemplate,
        tier: BudgetTier,
        city: str,
        service: str,
        exclusions: list[str],
    ) -> list[AdGroupProposal]:
        ad_groups: list[AdGroupProposal] = []
        exclusions_lower = {e.lower() for e in exclusions}

        for ag_tmpl in template.ad_groups:
            keywords = self._filter_keywords(ag_tmpl, tier, city, service, exclusions_lower)
            if not keywords:
                continue

            name = _resolve(ag_tmpl.name_template, city, service)
            placeholder_headlines = [_resolve(h, city, service) for h in _PLACEHOLDER_HEADLINES]
            placeholder_descriptions = [_resolve(d, city, service) for d in _PLACEHOLDER_DESCRIPTIONS]

            ad = AdProposal(
                headlines=placeholder_headlines,
                descriptions=placeholder_descriptions,
                final_url="https://example.com",
                path_segments=(city[:15], ""),
            )
            ad_groups.append(AdGroupProposal(name=name, keywords=keywords, ads=[ad]))

        return ad_groups

    def _filter_keywords(
        self,
        ag_tmpl,
        tier: BudgetTier,
        city: str,
        service: str,
        exclusions_lower: set[str],
    ) -> list[KeywordProposal]:
        keywords: list[KeywordProposal] = []
        for entry in ag_tmpl.keyword_bank:
            if tier == BudgetTier.MICRO and entry.priority == KeywordPriority.EXTENDED:
                continue
            text = _resolve(entry.text, city, service)
            if any(excl in text.lower() for excl in exclusions_lower):
                continue
            keywords.append(
                KeywordProposal(
                    text=text,
                    match_type=_MATCH_TYPE_MAP[entry.match_type],
                    estimated_cpc_micros=500_000,
                )
            )
        return keywords

    def _build_negatives(
        self,
        template: VerticalTemplate,
        brief: CampaignBrief,
    ) -> list[str]:
        negatives: list[str] = []

        # Standard Polish negatives (one anchor per category)
        negatives.extend(_STANDARD_NEGATIVE_ANCHORS)

        # Template negatives
        negatives.extend(template.negatives.all_negatives)

        # User exclusions
        negatives.extend(brief.exclusions)

        # Deduplicate preserving order
        seen: set[str] = set()
        result: list[str] = []
        for n in negatives:
            if n not in seen:
                seen.add(n)
                result.append(n)
        return result

    def _build_sitelinks(self, template: VerticalTemplate) -> list[SitelinkProposal]:
        return [
            SitelinkProposal(
                link_text=sl.text,
                description1=sl.description1 or "",
                description2=sl.description2 or "",
                final_url=f"https://example.com/{sl.path}" if sl.path else "https://example.com",
            )
            for sl in template.extensions.sitelinks
        ]

    def _build_callouts(
        self,
        template: VerticalTemplate,
        phone: str | None,
    ) -> list[CalloutProposal]:
        callouts = [CalloutProposal(text=c) for c in template.extensions.callouts]
        if phone:
            callouts.append(CalloutProposal(text=phone[:25]))
        return callouts

    def _build_structured_snippets(
        self,
        template: VerticalTemplate,
    ) -> list[StructuredSnippetProposal]:
        if not template.common_services:
            return []
        return [
            StructuredSnippetProposal(
                header=template.extensions.structured_snippet_category or "Usługi",
                values=[s[:25] for s in template.common_services[:10]],
            )
        ]
